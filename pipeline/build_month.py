def summarize_nutrition(items):
    total = {f: 0.0 for f in NUT_FIELDS}
    tw = 0.0
    n_unmatched = 0
    n_gagong = 0
    missing_list = []
    unmatched_list = []
    gagong_list = []
    nutri_source = {"food_db": [], "recipe_decompose": [], "gagong_db": []}
    for it in items:
        for f in NUT_FIELDS:
            total[f] += it["contrib"][f]
        tw += it["weight_g"]
        if not it["matched"]:
            n_unmatched += 1
            unmatched_list.append(it["display"])
        else:
            if it["missing"]:
                missing_list.append(f'{it["display"]}: ' + ",".join(it["missing"]))
            if it["source"] == "gagong_db":
                n_gagong += 1
                gagong_list.append(it["display"])
            if it["source"] in nutri_source:
                nutri_source[it["source"]].append(it["display"])

    recomputed = total["carb"] * 4 + total["protein"] * 4 + total["fat"] * 9
    diff_ratio = abs(recomputed - total["kcal"]) / total["kcal"] if total["kcal"] > 0 else 0
    reverse_ok = diff_ratio <= 0.10

    # Fulgoni et al.(2009) 원문 그대로: 100kcal 기준으로 정규화한 뒤 %DV를 "합"(sum, 평균 아님)한다.
    kcal_scale = 100.0 / total["kcal"] if total["kcal"] > 0 else 0
    ben = sum(min((total[db_f_map] * kcal_scale) / DV[nrf_f], 1) * 100 for nrf_f, db_f_map in
              zip(BENEFICIAL, ["protein", "fiber", "ca", "fe", "vitA", "vitC"]))
    dis = sum(min((total[db_f_map] * kcal_scale) / DV[nrf_f], 1) * 100 for nrf_f, db_f_map in
              zip(DISQUALIFYING, ["satFat", "sugar", "na"]))
    nrf = round(ben - dis, 1)

    n_missing_fields = sum(len(it["missing"]) for it in items if it["matched"])
    if n_unmatched == 0 and n_missing_fields == 0 and reverse_ok:
        confidence = "높음"
    elif reverse_ok and n_unmatched == 0 and n_missing_fields <= 4:
        confidence = "보통"
    else:
        confidence = "낮음"

    return total, tw, nrf, diff_ratio, reverse_ok, confidence, unmatched_list, gagong_list, missing_list, nutri_source


def compute_tray(lunch, cache):
    main = lunch.get("calculationMain", lunch["main"])
    shop, category = lunch["shop"], lunch["category"]
    sides = [s for s in lunch["sides"] if not is_self_or_junk(s)]
    # 2026-11-10 사용자 지정: 돈까스나베는 분해 시 쌀밥을 포함하므로, 중복되는 밥 사이드를 제거해
    # 밥을 쌀밥 하나로 통일한다(곡류군 중복 합산 방지).
    if lunch["main"] == "돈까스나베":
        sides = [s for s in sides if s not in ("흑미밥", "쌀밥", "잡곡밥", "현미밥", "기장밥", "보리밥")]
    # 2026-11-11 사용자 확인: 한양플라자(105) 즉석 코너는 공기밥이 항상 함께 제공되는데 원본 메뉴 텍스트에
    # 밥이 표기되지 않아 곡류군·열량이 통째로 빠져 있었다. 메인/사이드에 밥류가 없으면 쌀밥 210g을 추가한다.
    # (한식 등 다른 코너는 밥이 항상 나가지 않으므로 자동 추가하지 않는다 - 2026-11-11 사용자 확인.)
    extra_rice = None
    if shop == "105" and category == "즉석" and not has_rice_like(main, sides):
        extra_rice = ("쌀밥", 210, "즉석 코너 공기밥 - 원본 메뉴 미표기, 사용자 확인(2026-11-11)으로 항상 제공 적용; 일반 밥 1공기 210g")
    elif (lunch["date"], shop, lunch["main"]) in RICE_CONFIRMED_TRAYS and not has_rice_like(main, sides):
        extra_rice = ("쌀밥", 210, "공기밥 - 원본 메뉴 미표기, 해당 식판 사용자 개별 확인(2026-11-11)으로 추가; 일반 밥 1공기 210g")

    items = []
    for p, w, note in expand_main(main, shop, category, cache):
        items.append(build_item(p, w, note, cache))
    for s in sides:
        for p, w, note in expand_side(s, shop, category, cache, date=lunch["date"]):
            items.append(build_item(p, w, note, cache))
    if extra_rice:
        items.append(build_item(*extra_rice, cache))

    include_photo_confirmed_rice(items, lunch, cache)
    apply_reviewed_chip_portion(items, lunch, cache)
    apply_reviewed_side_rice_portion(items, lunch, cache)
    apply_reviewed_fries_portion(items, lunch, cache)
    apply_nov11_plaza_photo_review(items, lunch, cache)
    include_nov5_fishcake_photo_sides(items, lunch, cache)
    from approved_nov_nutrition import apply_approved_nutrition
    apply_approved_nutrition(items, lunch)
    total, tw, nrf, diff_ratio, reverse_ok, confidence, unmatched_list, gagong_list, missing_list, nutri_source = summarize_nutrition(items)

    exchange_units = None
    # 2026-11-04: 204(신소재공학관)는 기존에 08-24~09-19 구간만 식품교환단위를 계산했음 -
    # 사용자 지시로 10/26~11/6까지 범위 확장.
    if shop == "105" or (shop in ("401", "204") and "2026-08-24" <= lunch["date"] <= "2026-11-13"):
        exchange_units = compute_tray_exchanges(items, main, shop, lunch["date"])

    return {
        "date": lunch["date"], "shop": lunch["shop"], "shopName": lunch["shopName"],
        "category": lunch["category"], "main": lunch["main"], "calculationMain": main, "price": lunch["price"], "img": lunch["img"],
        "cat_idx": lunch.get("cat_idx", 0),
        "구성요소_목록": [it["display"] for it in items],
        "1인분_제공량_g": round(tw, 1),
        "kcal": round(total["kcal"], 1), "단백질_g": round(total["protein"], 1),
        "지방_g": round(total["fat"], 1), "탄수화물_g": round(total["carb"], 1),
        "당류_g": round(total["sugar"], 1), "식이섬유_g": round(total["fiber"], 1),
        "칼슘_mg": round(total["ca"], 1), "철_mg": round(total["fe"], 2),
        "비타민A_ugRAE": round(total["vitA"], 1), "비타민C_mg": round(total["vitC"], 1),
        "포화지방_g": round(total["satFat"], 2), "나트륨_mg": round(total["na"], 1),
        "NRF6.3": nrf, "역산검증_오차율": round(diff_ratio * 100, 1), "역산검증_일치여부": reverse_ok,
        "신뢰도": confidence,
        "미매칭_항목": unmatched_list, "가공식품DB_출처_항목": gagong_list, "결측_필드": missing_list,
        "영양_매칭DB": nutri_source,
        "식품교환단위": exchange_units,
        "item_detail": items,
    }


