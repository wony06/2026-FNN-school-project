def build_item(name, weight_g, weight_note, cache):
    m = cache.get(name)
    if m is None:
        return {"display": name, "matched": False, "weight_g": weight_g, "weight_note": weight_note,
                "contrib": {f: 0 for f in NUT_FIELDS}, "missing": NUT_FIELDS[:], "source": None}
    per100 = m["per100"]
    missing = [f for f in NUT_FIELDS if per100.get(f) is None]
    src = m.get("source")
    # 2026-11-03: 영양소 계산용 중량과 "표시용 1인분 중량"(weight_g, classify_*_weight에서
    # 이미 DB 1회분 값 또는 이 표의 값으로 정해짐)을 분리한다. recipe_decompose는 레시피에
    # 물이 안 적힌 경우가 많아 재료 매칭 합계(total_parsed_weight_g)가 표시용 중량보다 작을
    # 수 있는데, per100도 그 합계 기준으로 계산됐으므로 영양소 계산은 항상 그 합계 그대로
    # 써야 자체 일관성이 유지된다(표시중량을 곱하면 과다산정됨). food_db/gagong_db는 매칭된
    # 1회분 값이 이미 weight_g에 반영돼 있으므로 둘이 같아 추가 분기가 필요 없다.
    nutrition_weight_g = m.get("total_parsed_weight_g", weight_g) if src == "recipe_decompose" else weight_g
    contrib = {f: (per100.get(f) or 0) * nutrition_weight_g / 100.0 for f in NUT_FIELDS}
    return {"display": name, "matched": True, "weight_g": weight_g, "weight_note": weight_note,
            "contrib": contrib, "missing": missing, "source": src, "db_name": m.get("name")}


def all_match_names(lunch):
    """이 트레이 계산에 실제로 매칭을 시도할 원자 단위 이름 전체(& / * / 분해 반영).
    run_pipeline.py의 매칭 단계가 압축 표기가 아니라 분해된 실제 이름 기준으로
    캐시를 채우도록 build_month와 동일한 분해 로직을 그대로 재사용한다."""
    main = lunch.get("calculationMain", lunch["main"])
    shop, category = lunch["shop"], lunch["category"]
    sides = [s for s in lunch["sides"] if not is_self_or_junk(s)]
    names = [p for p, _, _ in expand_main(main, shop, category)]
    for s in sides:
        names.extend(p for p, _, _ in expand_side(s, shop, category))
    return names


