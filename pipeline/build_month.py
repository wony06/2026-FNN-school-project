def is_self_or_junk(tok):
    if not tok:
        return True
    if tok in SELF_KEYWORDS:
        return True
    # 2026-11-08: "~사리"(라면사리·우동사리·당면사리 등 추가면)는 사용자 지시로 메뉴에서 아예
    # 제거하고, 메뉴명(메인)만으로 매칭한다. (예: "부대찌개&라면사리" -> 부대찌개만)
    if tok.endswith("사리"):
        return True
    if tok in OPTIONAL_EXCLUDE_KEYWORDS:
        return True
    if "self" in tok.lower():
        return True
    if not re.search(r"[가-힣a-zA-Z0-9]", tok):  # 순수 기호(&, / 등)만 있는 토큰
        return True
    return False

